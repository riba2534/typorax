import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dirs = execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable'], { cwd: root, encoding: 'utf8' }).trim().split('\n').slice(1);
const packages = new Map();
for (const dir of dirs) {
  const info = JSON.parse(readFileSync(resolve(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir).filter(name => /^(license|licence|copying|notice)(\.|$)/i.test(name)).sort();
  if (!files.length) throw new Error('Missing license: ' + info.name);
  const notices = files.map(name => ({ name, text: readFileSync(resolve(dir, name), 'utf8').trim() }));
  packages.set(info.name + '@' + info.version, { info, notices });
}
let output = '# Third-party notices\n\n';
output += 'Generated by npm run licenses from the locked production dependency tree. This conservative inventory includes transitive packages that may be tree-shaken from the final bundle. Dependencies are unmodified and retain their individual licenses; TyporaX’s MIT license applies only to its own code.\n\n';
output += 'DOMPurify is used under its Apache-2.0 option. ELK/elkjs is available under EPL-2.0; its corresponding source and build instructions are available from https://github.com/kieler/elkjs and https://github.com/eclipse-elk/elk. The exact version is listed below and recoverable through package-lock.json. No ELK source modifications are made. Redistribution must retain its EPL notices and source availability. KaTeX fonts and code are included under the notices distributed by KaTeX.\n\n';
for (const [key, { info, notices }] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const repository = typeof info.repository === 'string' ? info.repository : info.repository?.url;
  output += '## ' + key + '\n\n';
  output += '- License: ' + (info.license || (info.name === 'khroma' ? 'MIT (see packaged license)' : 'See license text below')) + '\n';
  output += '- Package: https://www.npmjs.com/package/' + info.name + '/v/' + info.version + '\n';
  if (repository) output += '- Upstream: ' + repository + '\n';
  output += '\n';
  for (const notice of notices) output += '### ' + notice.name + '\n\n' + notice.text + '\n\n';
}
writeFileSync(resolve(root, 'THIRD_PARTY_NOTICES.md'), output.trimEnd() + '\n');
console.log('Wrote notices for ' + packages.size + ' production packages.');
